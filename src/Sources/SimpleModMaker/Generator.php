if (! defined('SMF'))
	die('No direct access...');

namespace Bugo\SimpleModMaker;

use Bugo\SimpleModMaker\Hooks\HookFactory;
use Nette\PhpGenerator\ClassType;
use Nette\PhpGenerator\Method;
use Nette\PhpGenerator\PhpFile;
use Nette\PhpGenerator\PhpNamespace;

class Generator
{
	/**
	 * The runtime check that separates the code branches of a mod built for
	 * both SMF versions at once.
	 */
	private const SMF3_CHECK = "version_compare(SMF_VERSION, '3.0', '>=')";

	public function generate(array &$skeleton, string $classname, string $snakeName): array
	{
		$skeleton['callbacks'] = $this->collectCallbacks($skeleton['options'], $snakeName);

		[$namespace, $class] = $this->createClassStructure($skeleton, $classname);

		$this->generateHooksMethods($class, $skeleton, $classname, $snakeName);
		$this->generateLegacyTaskMethods($class, $skeleton);
		$this->generateSettingsMethods($class, $skeleton, $classname, $snakeName);

		$tasks = [];

		$this->generateScheduledTasks($tasks, $skeleton, $classname);
		$this->generateBackgroundTasks($tasks, $skeleton, $classname);
		$this->generateTaskExamples($namespace, $class, $skeleton, $classname, $tasks);

		$filename = (empty($skeleton['make_dir']) ? $skeleton['filename'] : 'Integration') . '.php';
		$content  = $this->getGeneratedContent($namespace, $filename, $skeleton);

		return [
			'content' => $content,
			'tasks'   => $tasks,
		];
	}

	private function createClassStructure(array $skeleton, string $classname): array
	{
		if (empty($skeleton['make_dir'])) {
			$namespace = new PhpNamespace($skeleton['namespace']);
			$class     = $namespace->addClass($classname);
		} else {
			$namespace = new PhpNamespace($skeleton['namespace'] . '\\' . $classname);
			$class     = $namespace->addClass('Integration');
		}

		if (in_array($skeleton['smf_target_version'], ['3.0', '2.1/3.0'], true)) {
			$this->addSMF3Imports($namespace);
		}

		$class->addComment('Generated by ' . SMM_NAME);

		if ($skeleton['smf_target_version'] === '2.1/3.0') {
			$class->addComment(PHP_EOL . 'The generated code runs on both SMF versions out of the box. Optionally, you can use the https://github.com/dragomano/smf-compat package to make it cleaner');
		}

		return [$namespace, $class];
	}

	/**
	 * Whether the generated code must use the modern API of SMF 3.0.
	 */
	private function needsSmf3Code(array $skeleton): bool
	{
		return in_array($skeleton['smf_target_version'], ['3.0', '2.1/3.0'], true);
	}

	/**
	 * Whether the generated code must use the legacy API of SMF 2.1.
	 */
	private function needsLegacyCode(array $skeleton): bool
	{
		return in_array($skeleton['smf_target_version'], ['2.1', '2.1/3.0'], true);
	}

	private function isMixedTarget(array $skeleton): bool
	{
		return $skeleton['smf_target_version'] === '2.1/3.0';
	}

	/**
	 * @param list<string> $legacyLines
	 * @param list<string> $modernLines
	 */
	private function addDualBodies(Method $method, array $legacyLines, array $modernLines): void
	{
		$method->addBody('if (' . self::SMF3_CHECK . ') {');

		foreach ($modernLines as $line) {
			$method->addBody($this->indentLines($line));
		}

		$method->addBody('} else {');

		foreach ($legacyLines as $line) {
			$method->addBody($this->indentLines($line));
		}

		$method->addBody('}' . PHP_EOL);
	}

	/**
	 * Adds the bodies of both API variants: separately generated for a single
	 * target version, or wrapped into a runtime version check for the mixed one.
	 *
	 * @param list<string> $legacyLines
	 * @param list<string> $modernLines
	 */
	private function attachVariantBodies(Method $method, array $skeleton, array $legacyLines, array $modernLines): void
	{
		if ($this->isMixedTarget($skeleton)) {
			if ($legacyLines === [] && $modernLines === []) {
				return;
			}

			$this->addDualBodies($method, $legacyLines, $modernLines);

			return;
		}

		foreach ($this->needsSmf3Code($skeleton) ? $modernLines : $legacyLines as $line) {
			$method->addBody($line);
		}
	}

	private function addSMF3Imports(PhpNamespace $namespace): void
	{
		$namespace->addUse(\SMF\Actions\Admin\ACP::class);
		$namespace->addUse(\SMF\Config::class);
		$namespace->addUse(\SMF\Db\DatabaseApi::class, 'Db');
		$namespace->addUse(\SMF\IntegrationHook::class);
		$namespace->addUse(\SMF\Lang::class);
		$namespace->addUse(\SMF\Menu::class);
		$namespace->addUse(\SMF\Theme::class);
		$namespace->addUse(\SMF\User::class);
		$namespace->addUse(\SMF\Utils::class);
	}

	private function generateHooksMethods(ClassType $class, array $skeleton, string $classname, string $snakeName): void
	{
		$context = ['smm_skeleton' => $skeleton];

		$hooks = $class->addMethod('hooks')->setReturnType('void');

		if (empty($skeleton['hooks'])) {
			if ($this->needsSmf3Code($skeleton)) {
				$hooks->addBody("// IntegrationHook::add('integrate_hook_name', self::class . '::methodName#');");
			}

			if ($this->needsLegacyCode($skeleton)) {
				$hooks->addBody("// add_integration_function('integrate_hook_name', self::class . '::methodName#', false);");
			}
		}

		// The registrations are collected first, so all of them share a single
		// version check instead of repeating it for every hook
		$legacyLines = [];
		$modernLines = [];

		foreach ($skeleton['hooks'] as $hook) {
			$methodName = $this->getMethodName($hook);

			if ($this->needsSmf3Code($skeleton)) {
				$modernLines[] = 'IntegrationHook::add(' . var_export($hook, true) . ", self::class . '::" . $methodName . "#');";
			}

			if ($this->needsLegacyCode($skeleton)) {
				$legacyLines[] = 'add_integration_function(' . var_export($hook, true) . ", self::class . '::" . $methodName . "#', false);";
			}

			$hooks->addComment("@uses $methodName");

			$method            = $class->addMethod($methodName);
			$hookInstance      = HookFactory::create($hook, $context, $classname, $snakeName);
			$withArea1Settings = $hook === Hook::GENERAL_MOD_SETTINGS && $skeleton['settings_area'] === 1;

			if ($hookInstance !== null) {
				$parameters = $hookInstance->getParameters();

				foreach ($parameters as $param => $data) {
					$parameter = isset($data[2]) ? $method->addParameter($param, $data[2]) : $method->addParameter($param);
					$parameter->setType($data[0]);

					if (! empty($data[1])) {
						$parameter->setReference();
					}
				}

				$method->setReturnType($hookInstance->getReturnType());

				$dualBody = $this->isMixedTarget($skeleton) ? $hookInstance->getDualBody() : null;

				if ($dualBody !== null) {
					$this->addDualBodies($method, $dualBody['legacy'], $dualBody['modern']);
				} else {
					foreach ($hookInstance->getBody() as $body) {
						$method->addBody($body);
					}
				}
			}

			// Default settings are initialized right in this hook
			if ($withArea1Settings) {
				$area1LegacyLines = $this->getArea1SettingsLines($skeleton, $classname, $snakeName, '2.1');
				$area1ModernLines = $this->getArea1SettingsLines($skeleton, $classname, $snakeName, '3.0');

				$this->attachVariantBodies($method, $skeleton, $area1LegacyLines, $area1ModernLines);
			}
		}

		$this->attachVariantBodies($hooks, $skeleton, $legacyLines, $modernLines);
	}

	/**
	 * @return list<string>
	 */
	private function getArea1SettingsLines(array $skeleton, string $classname, string $snakeName, string $variant): array
	{
		if (! $this->variantApplies($skeleton, $variant)) {
			return [];
		}

		$lines = [];

		// The globals of the legacy branch come first
		if ($variant === '2.1') {
			$globals = [];

			if (! empty($this->getDefaultSettings($skeleton, $snakeName))) {
				$globals[] = '$modSettings';
			}

			if ($this->hasSelectOptions($skeleton)) {
				$globals[] = '$txt';
			}

			if (! empty($globals)) {
				$lines[] = 'global ' . implode(', ', $globals) . ';' . PHP_EOL;
			}
		}

		if (TemplateUtil::needsTemplate($skeleton)) {
			$lines[] = $this->getLoadTemplateLine($classname, $variant);
		}

		$lines = array_merge($lines, $this->getDefaultSettingsLines($skeleton, $snakeName, $variant));

		return array_merge($lines, $this->getConfigVarsLines($skeleton, $snakeName, $variant));
	}

	private function generateLegacyTaskMethods(ClassType $class, array $skeleton): void
	{
		foreach ($skeleton['legacy_tasks'] as $task) {
			$taskMethod = $class->addMethod($task['method']);
			$hookName   = empty($task['regularity']) ? Hook::DAILY_MAINTENANCE : Hook::WEEKLY_MAINTENANCE;

			$taskMethod->addComment("Simple task via $hookName hook");
			$taskMethod->setReturnType('void');

			if ($this->isMixedTarget($skeleton)) {
				$taskMethod->addBody('if (' . self::SMF3_CHECK . ') {');
				$taskMethod->addBody("\t// Add your code here, using Db::\$db for database access");
				$taskMethod->addBody('} else {');
				$taskMethod->addBody("\tglobal \$smcFunc;" . PHP_EOL);
				$taskMethod->addBody("\t// Add your code here");
				$taskMethod->addBody('}' . PHP_EOL);

				continue;
			}

			if ($this->needsLegacyCode($skeleton)) {
				$taskMethod->addBody("global \$smcFunc;" . PHP_EOL);
			}

			$taskMethod->addBody('// Add your code here');
		}
	}

	private function generateSettingsMethods(ClassType $class, array $skeleton, string $classname, string $snakeName): void
	{
		$hookKeys = array_flip($skeleton['hooks']);

		if ($skeleton['settings_area'] === 2) {
			$this->generateSettingsArea2($class, $skeleton, $classname, $snakeName, $hookKeys);
		}

		if ($skeleton['settings_area'] === 3) {
			$this->generateSettingsArea3($class, $skeleton, $classname, $snakeName);
		}
	}

	private function generateSettingsArea2(ClassType $class, array $skeleton, string $classname, string $snakeName, array $hookKeys): void
	{
		$settings = $class->addMethod('settings');

		if (isset($hookKeys[Hook::ADMIN_SEARCH])) {
			$settings->addComment('@return array|void');

			$parameter = $settings->addParameter('return_config', false);
			$parameter->setType('bool');
		}

		$legacyLines = $this->getSettingsArea2Lines($skeleton, $classname, $snakeName, $hookKeys, '2.1');
		$modernLines = $this->getSettingsArea2Lines($skeleton, $classname, $snakeName, $hookKeys, '3.0');

		$this->attachVariantBodies($settings, $skeleton, $legacyLines, $modernLines);
	}

	/**
	 * @return list<string>
	 */
	private function getSettingsArea2Lines(array $skeleton, string $classname, string $snakeName, array $hookKeys, string $variant): array
	{
		if (! $this->variantApplies($skeleton, $variant)) {
			return [];
		}

		$hasDefaults = ! empty($this->getDefaultSettings($skeleton, $snakeName));

		$lines = [];

		if ($variant === '3.0') {
			$lines[] = "Lang::load(" . var_export($classname . (empty($skeleton['use_lang_dir']) ? '' : '/'), true) . ");" . PHP_EOL;
			$lines[] = "Utils::\$context['page_title'] = Utils::\$context['settings_title'] = Lang::\$txt['{$snakeName}_title'];";
			$lines[] = "Utils::\$context['post_url'] = Config::\$scripturl . '?action=admin;area=modsettings;save;sa=$snakeName';" . PHP_EOL;
		} else {
			$lines[] = "global \$context, \$txt, \$scripturl" . ($hasDefaults ? ", \$modSettings" : '') . ";" . PHP_EOL;
			$lines[] = "loadLanguage(" . var_export($classname . (empty($skeleton['use_lang_dir']) ? '' : '/'), true) . ");" . PHP_EOL;
			$lines[] = "\$context['page_title'] = \$context['settings_title'] = \$txt['{$snakeName}_title'];";
			$lines[] = "\$context['post_url'] = \$scripturl . '?action=admin;area=modsettings;save;sa=$snakeName';" . PHP_EOL;
		}

		if (TemplateUtil::needsTemplate($skeleton)) {
			$lines[] = $this->getLoadTemplateLine($classname, $variant);
		}

		if (! empty($skeleton['options'])) {
			$lines = array_merge($lines, $this->getDefaultSettingsLines($skeleton, $snakeName, $variant));
		}

		$lines[] = "\$config_vars = [];";

		$lines = array_merge($lines, $this->getConfigVarsLines($skeleton, $snakeName, $variant));

		if (isset($hookKeys[Hook::ADMIN_SEARCH])) {
			$lines[] = PHP_EOL . "if (\$return_config) {";
			$lines[] = "\treturn \$config_vars;";
			$lines[] = "}" . PHP_EOL;
		}

		if ($variant === '3.0') {
			$lines[] = "Menu::\$loaded['admin']->tab_data['description'] = Lang::\$txt['{$snakeName}_description'];" . PHP_EOL;
			$lines[] = '// Saving?';
			$lines[] = "if (isset(\$_GET['save'])) {";
			$lines[] = "\tUser::\$me->checkSession();" . PHP_EOL;
			$lines[] = "\t\$save_vars = \$config_vars;";
			$lines[] = "\tACP::saveDBSettings(\$save_vars);" . PHP_EOL;
			$lines[] = "\tUtils::redirectexit('action=admin;area=modsettings;sa=$snakeName');";
			$lines[] = '}' . PHP_EOL;
			$lines[] = 'ACP::prepareDBSettingContext($config_vars);';
		} else {
			$lines[] = "\$context[\$context['admin_menu_name']]['tab_data']['description'] = \$txt['{$snakeName}_description'];" . PHP_EOL;
			$lines[] = '// Saving?';
			$lines[] = "if (isset(\$_GET['save'])) {";
			$lines[] = "\tcheckSession();" . PHP_EOL;
			$lines[] = "\t\$save_vars = \$config_vars;";
			$lines[] = "\tsaveDBSettings(\$save_vars);" . PHP_EOL;
			$lines[] = "\tredirectexit('action=admin;area=modsettings;sa=$snakeName');";
			$lines[] = '}' . PHP_EOL;
			$lines[] = 'prepareDBSettingContext($config_vars);';
		}

		return $lines;
	}

	private function generateSettingsArea3(ClassType $class, array $skeleton, string $classname, string $snakeName): void
	{
		$settings = $class->addMethod('settings');

		$legacyLines = $this->getSettingsArea3Lines($skeleton, $classname, $snakeName, '2.1');
		$modernLines = $this->getSettingsArea3Lines($skeleton, $classname, $snakeName, '3.0');

		$this->attachVariantBodies($settings, $skeleton, $legacyLines, $modernLines);

		$this->generateSectionExample($class, $skeleton, $snakeName);
	}

	/**
	 * @return list<string>
	 */
	private function getSettingsArea3Lines(array $skeleton, string $classname, string $snakeName, string $variant): array
	{
		if (! $this->variantApplies($skeleton, $variant)) {
			return [];
		}

		$lines = [];

		if ($variant === '3.0') {
			if (TemplateUtil::needsTemplate($skeleton)) {
				$lines[] = $this->getLoadTemplateLine($classname, $variant);
			}

			$lines[] = "Utils::\$context['page_title'] = Lang::\$txt['{$snakeName}_title'];" . PHP_EOL;
			$lines[] = "\$subActions = [";
			$lines[] = "\t'section1'  => [\$this, 'sectionExample1'],";
			$lines[] = "\t//'section2' => [\$this, 'sectionExample2'],";
			$lines[] = "];" . PHP_EOL;
			$lines[] = "Menu::\$loaded['admin']->tab_data = [";
			$lines[] = "\t'title' => Lang::\$txt['{$snakeName}_title'],";
			$lines[] = "\t'description' => Lang::\$txt['{$snakeName}_description'],";
			$lines[] = "\t'tabs' => [";
			$lines[] = "\t\t'section1'  => [],";
			$lines[] = "\t\t//'section2'  => [],";
			$lines[] = "\t]";
			$lines[] = "];" . PHP_EOL;
			$lines[] = "\$subAction = isset(\$_REQUEST['sa']) && isset(\$subActions[\$_REQUEST['sa']]) ? \$_REQUEST['sa'] : 'section1';" . PHP_EOL;
			$lines[] = 'call_user_func($subActions[$subAction]);';
		} else {
			$lines[] = "global \$context, \$txt, \$sourcedir;" . PHP_EOL;

			if (TemplateUtil::needsTemplate($skeleton)) {
				$lines[] = $this->getLoadTemplateLine($classname, $variant);
			}

			$lines[] = "require_once \$sourcedir . '/ManageSettings.php';" . PHP_EOL;
			$lines[] = "\$context['page_title'] = \$txt['{$snakeName}_title'];" . PHP_EOL;
			$lines[] = "\$subActions = [";
			$lines[] = "\t'section1'  => [\$this, 'sectionExample1'],";
			$lines[] = "\t//'section2' => [\$this, 'sectionExample2'],";
			$lines[] = "];" . PHP_EOL;
			$lines[] = "\$context[\$context['admin_menu_name']]['tab_data'] = [";
			$lines[] = "\t'title' => \$txt['{$snakeName}_title'],";
			$lines[] = "\t'description' => \$txt['{$snakeName}_description'],";
			$lines[] = "\t'tabs' => [";
			$lines[] = "\t\t'section1'  => [],";
			$lines[] = "\t\t//'section2'  => [],";
			$lines[] = "\t]";
			$lines[] = "];" . PHP_EOL;
			$lines[] = "loadGeneralSettingParameters(\$subActions, 'section1');" . PHP_EOL;
			$lines[] = 'call_helper($subActions[$context[\'sub_action\']]);';
		}

		return $lines;
	}

	private function generateSectionExample(ClassType $class, array $skeleton, string $snakeName): void
	{
		$section = $class->addMethod('sectionExample1');
		$section->addComment('@return array|void');

		$parameter = $section->addParameter('return_config', false);
		$parameter->setType('bool');

		$legacyLines = $this->getSectionExampleLines($skeleton, $snakeName, '2.1');
		$modernLines = $this->getSectionExampleLines($skeleton, $snakeName, '3.0');

		$this->attachVariantBodies($section, $skeleton, $legacyLines, $modernLines);
	}

	/**
	 * @return list<string>
	 */
	private function getSectionExampleLines(array $skeleton, string $snakeName, string $variant): array
	{
		if (! $this->variantApplies($skeleton, $variant)) {
			return [];
		}

		$hasDefaults = ! empty($this->getDefaultSettings($skeleton, $snakeName));

		$lines = [];

		if ($variant === '3.0') {
			$lines[] = "Utils::\$context['page_title'] .= ' - ' . Lang::\$txt['{$snakeName}_section1_title'];";
			$lines[] = "Utils::\$context['post_url'] = Config::\$scripturl . '?action=admin;area=$snakeName;sa=section1;save';" . PHP_EOL;
		} else {
			$lines[] = "global \$context, \$txt, \$scripturl, \$sourcedir" . ($hasDefaults ? ", \$modSettings" : '') . ";" . PHP_EOL;
			$lines[] = "require_once \$sourcedir . '/ManageServer.php';" . PHP_EOL;
			$lines[] = "\$context['page_title'] .= ' - ' . \$txt['{$snakeName}_section1_title'];";
			$lines[] = "\$context['post_url'] = \$scripturl . '?action=admin;area=$snakeName;sa=section1;save';" . PHP_EOL;
		}

		$lines = array_merge($lines, $this->getDefaultSettingsLines($skeleton, $snakeName, $variant));

		$lines[] = "\$config_vars = [];";

		$lines = array_merge($lines, $this->getConfigVarsLines($skeleton, $snakeName, $variant));

		$lines[] = PHP_EOL . "if (\$return_config) {";
		$lines[] = "\treturn \$config_vars;";
		$lines[] = "}" . PHP_EOL;
		$lines[] = "if (isset(\$_GET['save'])) {";

		if ($variant === '3.0') {
			$lines[] = "\tUser::\$me->checkSession();" . PHP_EOL;
			$lines[] = "\tACP::saveDBSettings(\$config_vars);" . PHP_EOL;
			$lines[] = "\tUtils::redirectexit('action=admin;area=$snakeName;sa=section1');";
			$lines[] = '}' . PHP_EOL;
			$lines[] = 'ACP::prepareDBSettingContext($config_vars);';
		} else {
			$lines[] = "\tcheckSession();" . PHP_EOL;
			$lines[] = "\tsaveDBSettings(\$config_vars);" . PHP_EOL;
			$lines[] = "\tredirectexit('action=admin;area=$snakeName;sa=section1');";
			$lines[] = '}' . PHP_EOL;
			$lines[] = 'prepareDBSettingContext($config_vars);';
		}

		return $lines;
	}

	/**
	 * @return list<string>
	 */
	private function getDefaultSettingsLines(array $skeleton, string $snakeName, string $variant): array
	{
		$defaults = $this->getDefaultSettings($skeleton, $snakeName);

		if (empty($defaults)) {
			return [];
		}

		$lines = [
			'// Add default settings',
			'$addSettings = [];',
		];

		foreach ($defaults as $settingKey => $default) {
			if ($variant === '3.0') {
				$lines[] = "if (! isset(Config::\$modSettings[" . var_export($settingKey, true) . '])) {';
			} else {
				$lines[] = "if (! isset(\$modSettings[" . var_export($settingKey, true) . '])) {';
			}

			$lines[] = "\t\$addSettings[" . var_export($settingKey, true) . '] = ' . $default . ';';
			$lines[] = '}';
		}

		$lines[] = ($variant === '3.0' ? 'Config::updateModSettings($addSettings);' : 'updateSettings($addSettings);') . PHP_EOL;

		return $lines;
	}

	/**
	 * The default is written only when explicitly entered: an empty string
	 * means its absence, unlike '0' and other zero-ish values.
	 */
	private function getDefaultSettings(array $skeleton, string $snakeName): array
	{
		$defaults = [];

		foreach ($skeleton['options'] as $option) {
			$default = $this->getDefaultValue($option);

			if ($default !== null) {
				$defaults[$snakeName . '_' . $option['name']] = $default;
			}
		}

		return $defaults;
	}

	private function hasSelectOptions(array $skeleton): bool
	{
		foreach ($skeleton['options'] as $option) {
			if (in_array($option['type'], ['select', 'select-multiple'], true)) {
				return true;
			}
		}

		return false;
	}

	/**
	 * @return list<string>
	 */
	private function getConfigVarsLines(array $skeleton, string $snakeName, string $variant): array
	{
		$lines = [];

		if (! empty($skeleton['options'])) {
			foreach ($skeleton['options'] as $option) {
				$settingKey = $snakeName . '_' . $option['name'];

				if (in_array($option['type'], ['select-multiple', 'select'], true)) {
					$isMultiple = var_export($option['type'] === 'select-multiple', true);

					$option['type'] = 'select';

					$txtKey = $variant === '3.0' ? 'Lang::$txt' : '$txt';

					$lines[] =
						"\$config_vars[] = [" . var_export($option['type'], true) . ', ' . var_export($settingKey, true)
						. ', ' . $txtKey . '[' . var_export($settingKey . '_set', true) . "], 'multiple' => $isMultiple];";
				} else {
					$lines[] =
						"\$config_vars[] = [" . var_export($option['type'], true) . ', ' . var_export($settingKey, true) . '];';
				}
			}
		} else {
			$lines[] = '// $config_vars[] = [\'check\', ' . var_export($snakeName . '_enable', true) . '];';
		}

		return $lines;
	}

	private function collectCallbacks(array $options, string $snakeName): array
	{
		$callbacks = [];

		foreach ($options as $option) {
			if (($option['type'] ?? '') === 'callback' && ! empty($option['name'])) {
				$callbacks[] = $snakeName . '_' . $option['name'];
			}
		}

		return array_values(array_unique($callbacks));
	}

	private function getLoadTemplateLine(string $classname, string $variant): string
	{
		return ($variant === '3.0' ? 'Theme::loadTemplate(' : 'loadTemplate(')
			. var_export($classname, true) . ');' . PHP_EOL;
	}

	/**
	 * Whether the code of the given API variant must be generated at all.
	 */
	private function variantApplies(array $skeleton, string $variant): bool
	{
		return $variant === '3.0' ? $this->needsSmf3Code($skeleton) : $this->needsLegacyCode($skeleton);
	}

	private function generateScheduledTasks(array &$tasks, array &$skeleton, string $baseClassname): void
	{
		foreach ($skeleton['scheduled_tasks'] as $id => $task) {
			$classname = $this->toCamelCase($task['slug']);
			$filename  = $classname . '.php';

			$taskFqcn = $skeleton['namespace'] . '\\' . $baseClassname . '\\Tasks\\' . $classname;

			// Keep the doubled separators of the stored callable for any namespace depth
			$skeleton['scheduled_tasks'][$id]['callable'] =
				'\\\\' . str_replace('\\', '\\\\', $taskFqcn) . '::execute';

			if ($this->isMixedTarget($skeleton)) {
				$variants = [];

				foreach (['2.1', '3.0'] as $variant) {
					$variantSkeleton = array_replace($skeleton, ['smf_target_version' => $variant]);

					[$namespace, $class] = $this->createTaskClass(
						$variantSkeleton,
						$baseClassname,
						$classname,
						$this->getTaskParentClass($variantSkeleton, 'ScheduledTask')
					);

					$this->createExecuteMethod($class, $variantSkeleton)
						->addBody('// Return true if everything is OK')
						->addBody('return true;');

					$variants[] = [$namespace, $class];
				}

				$content = $this->getDualTaskContent($filename, $skeleton, $variants);
			} else {
				[$namespace, $class] = $this->createTaskClass(
					$skeleton,
					$baseClassname,
					$classname,
					$this->getTaskParentClass($skeleton, 'ScheduledTask')
				);

				$this->createExecuteMethod($class, $skeleton)
					->addBody('// Return true if everything is OK')
					->addBody('return true;');

				$content = $this->getGeneratedContent($namespace, $filename, $skeleton);
			}

			$tasks[$task['slug']]['content']  = $content;
			$tasks[$task['slug']]['filename'] = $filename;
		}
	}

	private function generateBackgroundTasks(array &$tasks, array &$skeleton, string $baseClassname): void
	{
		foreach ($skeleton['background_tasks'] as $id => $task) {
			$classname = $task['classname'];
			$filename  = $classname . '.php';

			$taskFqcn = $skeleton['namespace'] . '\\' . $baseClassname . '\\Tasks\\' . $classname;

			// Keep the doubled separators of the stored callable for any namespace depth
			$skeleton['background_tasks'][$id]['callable'] = '\\\\' . str_replace('\\', '\\\\', $taskFqcn);

			if ($this->isMixedTarget($skeleton)) {
				$variants = [];

				foreach (['2.1', '3.0'] as $variant) {
					$variantSkeleton = array_replace($skeleton, ['smf_target_version' => $variant]);

					[$namespace, $class] = $this->createTaskClass(
						$variantSkeleton,
						$baseClassname,
						$classname,
						$this->getTaskParentClass($variantSkeleton, 'BackgroundTask')
					);

					$this->fillBackgroundTask($namespace, $class, $variantSkeleton, $baseClassname, $classname, $task);

					$variants[] = [$namespace, $class];
				}

				$content = $this->getDualTaskContent($filename, $skeleton, $variants);
			} else {
				[$namespace, $class] = $this->createTaskClass(
					$skeleton,
					$baseClassname,
					$classname,
					$this->getTaskParentClass($skeleton, 'BackgroundTask')
				);

				$this->fillBackgroundTask($namespace, $class, $skeleton, $baseClassname, $classname, $task);

				$content = $this->getGeneratedContent($namespace, $filename, $skeleton);
			}

			$tasks[$classname]['content']  = $content;
			$tasks[$classname]['filename'] = $filename;
		}
	}

	private function fillBackgroundTask(PhpNamespace $namespace, ClassType $class, array $skeleton, string $baseClassname, string $filename, array $task): void
	{
		$namespace->addUse(\SMF\Db\DatabaseApi::class, 'Db');

		$method = $this->createExecuteMethod($class, $skeleton);

		if (empty($task['regularity'])) {
			$method->addBody('// Return true if everything is OK');
			$method->addBody('return true;');
		} else {
			$regularity = $task['regularity'] == 1 ? 1 : 7;
			$method->addBody('// Run task again if you need');
			$method->addBody("\$regularity = $regularity * 24 * 60 * 60;" . PHP_EOL);

			if ($skeleton['smf_target_version'] !== '3.0') {
				$method->addBody("return (bool) \$smcFunc['db_insert']('insert',");
			} else {
				$method->addBody("return (bool) Db::\$db->insert('insert',");
			}

			$method->addBody("\t'{db_prefix}background_tasks',");
			$method->addBody("\t[");
			$method->addBody("\t\t'task_file'    => 'string',");
			$method->addBody("\t\t'task_class'   => 'string',");
			$method->addBody("\t\t'task_data'    => 'string',");
			$method->addBody("\t\t'claimed_time' => 'int'");
			$method->addBody("\t],");
			$method->addBody("\t[");
			$method->addBody("\t\t" . var_export('$sourcedir/' . $baseClassname . '/Tasks/' . $filename, true) . ',');
			$method->addBody("\t\t'\\\\' . self::class,");
			$method->addBody("\t\t'',");
			$method->addBody("\t\ttime() + \$regularity");
			$method->addBody("\t],");
			$method->addBody("\t['id_task'],");
			$method->addBody("\t1");
			$method->addBody(");" . PHP_EOL);
		}
	}

	/**
	 * Assembles the task file that declares only the class variant matching
	 * the current forum version, so the same stored callable works on both.
	 *
	 * @param list<array{0: PhpNamespace, 1: ClassType}> $variants
	 */
	private function getDualTaskContent(string $filename, array $skeleton, array $variants): string
	{
		$printer = new Printer();

		$file = new PhpFile();
		$file->addComment($filename);

		$this->addLicenseBlock($file, $skeleton);

		$content = $printer->printFile($file);

		$uses = new PhpNamespace($variants[0][0]->getName());

		foreach ($variants as [$namespace]) {
			foreach ($namespace->getUses() as $alias => $name) {
				$uses->addUse($name, $alias === $this->getShortClassName($name) ? null : $alias);
			}
		}

		$content .= 'namespace ' . $uses->getName() . ";\n\n";

		foreach ($uses->getUses() as $alias => $name) {
			$content .= 'use ' . $name . ($alias !== $this->getShortClassName($name) ? ' as ' . $alias : '') . ";\n";
		}

		$content .= "\nif (" . self::SMF3_CHECK . ") {\n"
			. $this->indentLines(rtrim($printer->printClass($variants[1][1], $variants[1][0])))
			. "\n} else {\n"
			. $this->indentLines(rtrim($printer->printClass($variants[0][1], $variants[0][0])))
			. "\n}\n";

		return $content;
	}

	/**
	 * Shifts every non-empty line of the given code one level deeper,
	 * including the lines of embedded multi-line statements.
	 */
	private function indentLines(string $code): string
	{
		return preg_replace_callback('/^[^\n]/m', static fn (array $match): string => "\t" . $match[0], $code);
	}

	private function createTaskClass(array $skeleton, string $baseClassname, string $classname, string $parentClass): array
	{
		$namespace = new PhpNamespace($skeleton['namespace'] . '\\' . $baseClassname . '\\Tasks');

		// The parent import is ambiguous when its short name equals the class name
		if (strcasecmp($classname, $this->getShortClassName($parentClass)) !== 0) {
			$namespace->addUse($parentClass);
		}

		$class = $namespace->addClass($classname);
		$class->setExtends($parentClass);
		$class->addComment('Generated by ' . SMM_NAME);

		return [$namespace, $class];
	}

	private function getTaskParentClass(array $skeleton, string $parentName): string
	{
		return $skeleton['smf_target_version'] === '3.0'
			? 'SMF\Tasks\\' . $parentName
			: 'SMF_BackgroundTask';
	}

	private function createExecuteMethod(ClassType $class, array $skeleton): Method
	{
		$method = $class->addMethod('execute');
		$method->setReturnType('bool');

		if ($skeleton['smf_target_version'] !== '3.0') {
			$method->addBody('global $smcFunc;' . PHP_EOL);
		}

		$method->addBody('// Add your code here' . PHP_EOL);

		return $method;
	}

	private function generateTaskExamples(PhpNamespace $namespace, ClassType $class, array $skeleton, string $baseClassname, array $tasks): void
	{
		if (empty($tasks)) {
			return;
		}

		foreach ($skeleton['background_tasks'] as $task) {
			if (! array_key_exists($task['classname'], $tasks)) {
				continue;
			}

			$classname = $task['classname'];
			$filename  = $tasks[$classname]['filename'];
			$taskClass = $this->addTaskClassUse($namespace, $skeleton, $baseClassname, $classname);

			$method = $class->addMethod('run' . $task['classname']);
			$method->setReturnType('void');
			$method->addComment('Call this method to run a background task');

			$insertLines = [
				"\t'{db_prefix}background_tasks',",
				"\t[",
				"\t\t'task_file'  => 'string',",
				"\t\t'task_class' => 'string',",
				"\t\t'task_data'  => 'string'",
				"\t],",
				"\t[",
				"\t\t" . var_export('$sourcedir/' . $baseClassname . '/Tasks/' . $filename, true) . ',',
				"\t\t'\\\\' . " . $taskClass . '::class,',
				"\t\t''",
				"\t],",
				"\t['id_task']",
				");" . PHP_EOL,
			];

			if ($this->isMixedTarget($skeleton)) {
				$method->addBody('if (' . self::SMF3_CHECK . ') {');
				$method->addBody("\tDb::\$db->insert('insert',");

				foreach ($insertLines as $line) {
					$method->addBody("\t" . $line);
				}

				$method->addBody('} else {');
				$method->addBody("\tglobal \$smcFunc;" . PHP_EOL);
				$method->addBody("\t\$smcFunc['db_insert']('insert',");

				foreach ($insertLines as $line) {
					$method->addBody("\t" . $line);
				}

				$method->addBody('}' . PHP_EOL);

				continue;
			}

			if ($this->needsLegacyCode($skeleton)) {
				$method->addBody("global \$smcFunc;" . PHP_EOL);
				$method->addBody("\$smcFunc['db_insert']('insert',");
			} else {
				$method->addBody("Db::\$db->insert('insert',");
			}

			foreach ($insertLines as $line) {
				$method->addBody($line);
			}
		}
	}

	private function addTaskClassUse(PhpNamespace $namespace, array $skeleton, string $baseClassname, string $classname): string
	{
		$taskFqcn  = $skeleton['namespace'] . '\\' . $baseClassname . '\\Tasks\\' . $classname;
		$shortName = $this->getShortClassName($taskFqcn);

		$usedNames = array_map(
			strtolower(...),
			array_merge(
				array_keys($namespace->getUses()),
				array_keys($namespace->getClasses())
			)
		);

		if (in_array(strtolower($shortName), $usedNames, true)) {
			return '\\' . $taskFqcn;
		}

		$namespace->addUse($taskFqcn);

		return $shortName;
	}

	private function getGeneratedContent(PhpNamespace $namespace, string $filename, array $skeleton): string
	{
		$file = new PhpFile();
		$file->addNamespace($namespace);
		$file->addComment($filename);

		return (new Printer())->printFile($this->addLicenseBlock($file, $skeleton));
	}

	private function addLicenseBlock(PhpFile $file, array $skeleton): PhpFile
	{
		$license = $skeleton['license_data'];

		$file->addComment('');
		$file->addComment('@package ' . Serializer::phpComment((string) $skeleton['name']));
		$file->addComment('@link ' . Serializer::phpComment((string) $skeleton['site']));
		$file->addComment('@author ' . Serializer::phpComment((string) $skeleton['author']) . ' <' . Serializer::phpComment((string) $skeleton['email']) . '>');
		$file->addComment('@copyright ' . date('Y') . ' ' . Serializer::phpComment((string) $skeleton['author']));
		$file->addComment('@license ' . Serializer::phpComment((string) $license['link']) . ' ' . Serializer::phpComment((string) $license['full_name']));
		$file->addComment('');
		$file->addComment('@version ' . Serializer::phpComment((string) $skeleton['version']));

		return $file;
	}

	private function getDefaultValue(array $option): ?string
	{
		// An unticked checkbox is identical to the absent setting for SMF
		if ($option['type'] === 'check') {
			return ! empty($option['default']) ? var_export(true, true) : null;
		}

		if (trim((string) $option['default']) === '') {
			return null;
		}

		return var_export(match ($option['type']) {
			'int'             => (int) $option['default'],
			'float'           => (float) $option['default'],
			'select-multiple' => $this->getMultipleDefault((string) $option['default']),
			default           => (string) $option['default'],
		}, true);
	}

	private function getMultipleDefault(string $default): string
	{
		$values = array_values(array_unique(array_filter(
			array_map(trim(...), preg_split('/[|,]/', $default) ?: []),
			fn(string $value): bool => $value !== ''
		)));

		// SMF stores multiple selections as a JSON array
		return json_encode($values) ?: '[]';
	}

	private function getMethodName(string $hook): string
	{
		return lcfirst(str_replace(' ', '', ucwords(strtr($hook, ['integrate' => '', '_' => ' ']))));
	}

	private function toCamelCase(string $value): string
	{
		return str_replace(' ', '', ucwords(str_replace('_', ' ', $value)));
	}

	private function getShortClassName(string $fqcn): string
	{
		$pos = strrpos($fqcn, '\\');

		return $pos === false ? $fqcn : substr($fqcn, $pos + 1);
	}
